#!/usr/bin/env node
/**
 * Generate llms.txt + llms-full.txt from navigation map + philosophy genes.
 * Gene: repo.tooling.genetic_starter.agentstack_dx.gen1
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { readKitLock } from './lib/read-kit-lock.mjs';
import { KIT_ROOT, EXTENSIONS_DIR } from './lib/paths.mjs';
import { scanPhilosophyGenes } from './lib/scan-philosophy-genes.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

function parseArgs(argv) {
  let target = null;
  let kitRoot = KIT_ROOT;
  for (let i = 2; i < argv.length; i++) {
    if (argv[i] === '--target') target = argv[++i];
    else if (argv[i] === '--kit-root') kitRoot = argv[++i];
    else if (argv[i] === '--help' || argv[i] === '-h') {
      console.log('Usage: node generate-llms-txt.mjs [--target <project>] [--kit-root <kit>]');
      process.exit(0);
    }
  }
  return { target: resolveTarget(target, kitRoot), kitRoot: path.resolve(kitRoot) };
}

/** Consumer project or kit fixture when run from monorepo maintainer context. */
function resolveTarget(targetArg, kitRoot) {
  if (targetArg) return path.resolve(targetArg);
  const cwd = process.cwd();
  if (fs.existsSync(path.join(cwd, 'docs/ai/AI_NAVIGATION_MAP.md'))) return cwd;
  const fixture = path.join(kitRoot, 'fixtures/empty-node-project');
  if (fs.existsSync(path.join(fixture, 'docs/ai/AI_NAVIGATION_MAP.md'))) return fixture;
  return cwd;
}

function readDocsBaseUrl(target, kitRoot) {
  const extPath = path.join(kitRoot, 'extensions/agentstack/extension.manifest.json');
  if (fs.existsSync(extPath)) {
    const em = JSON.parse(fs.readFileSync(extPath, 'utf8'));
    if (em.docsBaseUrl) return em.docsBaseUrl.replace(/\/$/, '');
  }
  return null;
}

function extractMapRows(mapText) {
  const rows = [];
  for (const line of mapText.split('\n')) {
    if (!line.trim().startsWith('|')) continue;
    if (line.includes('---')) continue;
    const cols = line
      .split('|')
      .map((c) => c.trim())
      .filter(Boolean);
    if (cols.length < 3 || cols[0] === 'Genetic tag') continue;
    const tag = cols[0].replace(/`/g, '');
    if (tag.startsWith('*') || tag.startsWith('(')) continue;
    rows.push({ tag, path: cols[1], note: cols[2] });
  }
  return rows;
}

function walkGenes(genesDir) {
  return scanPhilosophyGenes(genesDir).map((g) => ({
    tag: g.tag,
    rel: `philosophy/genes/${g.rel}`,
    intent: g.intent,
  }));
}

function shouldSkipForProfile(profile) {
  return profile === 'minimal';
}

function main() {
  const { target, kitRoot } = parseArgs(process.argv);
  const { lock } = readKitLock(target);
  const profile = lock?.profile || 'standard';
  if (shouldSkipForProfile(profile)) {
    console.log('generate-llms-txt: skip (minimal profile — navigation map stub only)');
    process.exit(0);
  }

  const mapPath = path.join(target, 'docs/ai/AI_NAVIGATION_MAP.md');
  if (!fs.existsSync(mapPath)) {
    console.error('Missing docs/ai/AI_NAVIGATION_MAP.md');
    process.exit(1);
  }

  const mapText = fs.readFileSync(mapPath, 'utf8');
  const rows = extractMapRows(mapText);
  const genes = walkGenes(path.join(target, 'philosophy/genes'));
  const docsBase = readDocsBaseUrl(target, kitRoot);
  const project = path.basename(target);

  const curated = [
    `# ${project} — Agent documentation (llms.txt)`,
    '',
    '> Generated by genetic-ai-starter `generate-llms-txt.mjs`. Curated navigation for LLM agents.',
    '',
    '## Read order',
    '',
    '1. `docs/ai/AI_NAVIGATION_MAP.md` — tier registry',
    '2. Local `AI_INDEX.md` beside the subsystem you touch',
    '3. `philosophy/genes/` — genetic tags (intent, not full prose)',
    '',
    '## Tier entries (from map)',
    '',
    ...rows.map((r) => `- \`${r.tag}\` — ${r.note} (${r.path})`),
    '',
    '## Philosophy genes (summary)',
    '',
    ...genes.slice(0, 40).map((g) => `- \`${g.tag}\` — ${g.intent || g.rel}`),
  ];

  if (genes.length > 40) {
    curated.push('', `_(${genes.length - 40} more genes — see llms-full.txt)_`);
  }

  if (docsBase) {
    curated.push('', '## Upstream docs', '', `- ${docsBase}`);
  }

  const full = [
    `# ${project} — Full agent documentation index`,
    '',
    '> Generated by genetic-ai-starter `generate-llms-txt.mjs`.',
    '',
    '## Navigation map',
    '',
    mapText.trim(),
    '',
    '## Philosophy genes',
    '',
    ...genes.map((g) => `### \`${g.tag}\`\n\n- Path: \`${g.rel}\`\n${g.intent ? `- Intent: ${g.intent}\n` : ''}`),
  ];

  const llmsPath = path.join(target, 'llms.txt');
  const fullPath = path.join(target, 'llms-full.txt');
  fs.writeFileSync(llmsPath, `${curated.join('\n')}\n`, 'utf8');
  fs.writeFileSync(fullPath, `${full.join('\n')}\n`, 'utf8');
  console.log('Wrote:', llmsPath);
  console.log('Wrote:', fullPath);
  console.log(`generate-llms-txt OK (${rows.length} map rows, ${genes.length} genes)`);
}

main();
